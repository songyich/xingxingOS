// ============================================================================
//  include/kernel/serial.hpp —— COM1 串口输出
//  ---------------------------------------------------------------------------
//  为什么内核要带串口？
//    串口是最古老、最简单的输出设备：往一个 I/O 端口写一个字节，
//    它就会从线上发出去，不需要任何驱动、不依赖显卡、不依赖图形模式。
//    所以当屏幕一片漆黑、或者内核刚崩在早期时，串口是唯一还能说话的通道。
//
//  QEMU 下怎么看到串口输出：
//    -serial file:serial.log   落盘
//    -serial stdio             直接打到终端
//    -serial telnet:...        远程
//
//  真实机器上用一根串口线（或 USB 转串口）接到另一台电脑的串口工具即可。
// ============================================================================
#pragma once

#include <kernel/types.h>

namespace serial {

// COM1 的标准端口基址
constexpr u16 COM1 = 0x3F8;

// 初始化串口：波特率 115200，8 位数据位、无校验、1 位停止位
// 返回是否初始化成功（芯片不存在时返回 false）
bool init();

// 串口是否可用
bool ready();

// 发送一个字符
void putc(char c);

// 发送以 '\0' 结尾的字符串
void puts(const char* str);

}  // namespace serial
