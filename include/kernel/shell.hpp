// ============================================================================
//  include/kernel/shell.hpp —— 交互式命令行 shell
//  ---------------------------------------------------------------------------
//  shell 是什么？
//    一个不断重复「读一行 -> 解析 -> 执行 -> 再读下一行」的循环（REPL）。
//    它本身不实现任何功能，只是把用户输入的名字和命令表里的条目对上，
//    然后调用对应的函数。这种「表驱动」的写法让加命令变得非常廉价：
//    写一个函数、往表里加一行、完事。
//
//  本阶段的能力边界：
//    内核现在有屏幕、键盘、定时器、物理内存、虚拟内存、堆，但**还没有文件系统**
//    和**多任务**（那是阶段 6、7 的事）。
//    所以像 ls、cat、ps 这些依赖那两样的命令暂时不存在——
//    但凡在当前能力范围内能实现的，都已经做了。
// ============================================================================
#pragma once

#include <kernel/types.h>

namespace shell {

// 单行最多能输入多少字符
constexpr int MAX_LINE = 256;

// 记住多少条历史命令
constexpr int HISTORY_COUNT = 16;

// ---------------------------------------------------------------------------
//  命令处理函数的签名
//  argc / argv 的含义和 C 语言 main 函数完全一致：
//    argv[0] 是命令本身，argv[1] 起是参数
// ---------------------------------------------------------------------------
using command_fn = void (*)(int argc, const char** argv);

// ---------------------------------------------------------------------------
//  命令表条目
// ---------------------------------------------------------------------------
struct Command {
    const char* name;        // 命令名
    const char* usage;       // 用法提示（help 会打印）
    const char* desc;        // 一句话说明
    command_fn  fn;          // 处理函数
};

// 启动 shell（不会返回，除非用户执行了 reboot/halt）
[[noreturn]] void run();

// ---------------------------------------------------------------------------
//  辅助接口（其他模块也能用）
// ---------------------------------------------------------------------------

// 手动执行一条命令（比如开机自动执行、或者将来做脚本）
void execute(const char* line);

// 打印命令表（help 命令用）
void print_commands();

// 当前输入了多少条命令（uptime 之类的可以顺便显示）
u32 command_count();

}  // namespace shell
