// ============================================================================
//  include/kernel/mouse.hpp —— 鼠标指针绘制
//  ---------------------------------------------------------------------------
//  只负责"把指针画到帧缓冲上"这一件最小的事。
//  PS/2 初始化、数据包解析、坐标累加都在用户态 mouse 服务里做。
// ============================================================================
#pragma once

#include <kernel/types.h>

namespace mouse {

void init();                     // 初始化：指针放到屏幕中央
bool available();                // 帧缓冲可用才算可用（文本模式没有鼠标指针）
void move_to(int x, int y);      // 移到绝对坐标
void move_by(int dx, int dy);    // 相对移动
void hide();                     // 擦掉指针（终端重绘/清屏时调用）
void show();                     // 重新画指针（清屏/重绘之后调用）

// ---------------------------------------------------------------------------
//  invalidate()：丢弃指针状态（切换渲染目标时必须调用）
// ---------------------------------------------------------------------------
//  指针的"背景备份"是**像素**，属于**当前渲染目标**。
//  开机动画会在"真帧缓冲"和"离屏缓冲"之间切换（fb::set_target），
//  切换后旧的备份像素属于另一块内存 —— 如果继续用它 restore，
//  就会把离屏里的内容写到真屏上，表现为屏幕上凭空多出一块色块。
//
//  实测复现：每次回车（终端 hide/show 一次）就在屏幕上多留一块，
//  以及开机后看到"两个鼠标"（一个是从离屏推上来的静态残影）。
//
//  所以切换渲染目标时必须调 invalidate()：只丢状态，**不恢复像素**。
// ---------------------------------------------------------------------------
void invalidate();

//  查询指针当前是否画在屏幕上。
//  滚屏前要据此判断"需不需要先擦掉" ——
//  滚屏会搬像素，不擦掉的话指针会被搬到上一行变成永久残影。
bool visible();
u32  center();                   // 移到屏幕正中，返回 (y<<16)|x
int  x();
int  y();

}   // namespace mouse
