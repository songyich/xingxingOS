// ============================================================================
//  include/kernel/printf.hpp —— 内核格式化输出 kprintf
//  ---------------------------------------------------------------------------
//  为什么不用 printf？
//    它来自 libc，而 libc 背后假设有操作系统提供「文件描述符」「写系统调用」。
//    内核本身就是那个操作系统，没有更底层的东西可依赖，只能自己实现。
//
//  支持的格式（% 开头）：
//    %s    字符串
//    %d %i 有符号十进制整数
//    %u    无符号十进制整数
//    %x %X 十六进制（小写 / 大写）
//    %p    指针，等价于 0x 开头的 16 位十六进制
//    %c    单个字符
//    %%    字面上的百分号
//
//  可选的修饰（跟标准 printf 一致）：
//    标志   '-' 左对齐   '+' 正数带正号   ' ' 正数带空格   '0' 用 0 填充
//    宽度   数字或 '*'（宽度从参数里取）
//    长度   'hh' 'h' 'l' 'll'
//
//  kprintf 会同时写到屏幕和串口，这样 QEMU 无窗口时也能从串口拿到日志。
// ============================================================================
#pragma once

#include <kernel/types.h>

// 返回值：实际输出的字符数（与标准 printf 一致）
extern "C" int kprintf(const char* fmt, ...);

// 只输出到串口（kprintf 内部用，也可在终端还没初始化时应急）
int kprintf_serial(const char* fmt, ...);

// ---------- 底层：把已经格式化好的一段文本送出去 ----------
namespace console {

void putc(char c);                       // 同时写屏幕 + 串口
void puts(const char* str);
void puts_n(const char* str, int len);

}  // namespace console
