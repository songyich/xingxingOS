// ============================================================================
//  include/kernel/supervisor.hpp —— 服务监管（崩溃自愈）
//  ---------------------------------------------------------------------------
//  【微内核的兑现点】
//  微内核把驱动挪到用户态，代价是 IPC 开销。
//  但收益必须是：**一个服务崩了，系统不跟着死**。
//
//  改造前（阶段 7 完成时的状态）：
//    任何异常一律 `内核已停止运行` + hlt。
//    用户态服务崩了整个系统死掉 —— **有开销、没收益**。
//
//  本模块要做的：
//    1. 用户态异常 → 只标记该线程 DEAD，不 panic
//    2. 唤醒所有等它回复的线程（否则它们永久卡死）
//    3. 自动重新拉起服务（**复用同一个 tid**，见下方说明）
//    4. 崩溃次数过多则放弃重启，避免无限刷屏
//
//  ⚠️ 为什么 respawn 必须**复用 tid**？
//    服务目录（svcdir）里登记的是 tid，各服务之间也直接持有 tid 常量
//    （TID_KEYBOARD=3 等）。如果重建时分配新 tid，
//    所有持有旧 tid 的引用全部失效 —— 键盘服务会"复活但没人找得到它"。
//    复用槽位则 tid 不变，其他服务**完全无感**。
// ============================================================================
#pragma once

#include <kernel/types.h>

namespace supervisor {

constexpr int MAX_WATCHED = 16;

// 单个服务连续崩溃多少次后放弃重启
constexpr int MAX_RESTART = 5;

void init();

// ---------------------------------------------------------------------------
//  登记一个被看护的服务（创建服务进程之后调用）
// ---------------------------------------------------------------------------
void watch(int tid, const char* name, u64 entry_virt, int priority);

// ---------------------------------------------------------------------------
//  线程死亡通知
//  -------------------------------------------------------------------------
//  由异常处理 / kill / 正常退出调用。
//  返回 true = 这个 tid 是被看护的服务，已登记待重启。
// ---------------------------------------------------------------------------
bool notify_dead(int tid);

// ---------------------------------------------------------------------------
//  执行重启（在时钟中断里调用）
//  -------------------------------------------------------------------------
//  为什么不立刻在异常上下文里重启？
//    异常时正处在中断栈上，做"分配栈、建页表、构造现场"这类
//    可能再次触发内存访问的操作很危险。延后到普通上下文更安全。
// ---------------------------------------------------------------------------
void tick();

// ---------------------------------------------------------------------------
//  主动杀掉一个进程（Sys::KILL）
//  -------------------------------------------------------------------------
//  返回 0 = 成功；-1 = 参数非法；-2 = 不允许
// ---------------------------------------------------------------------------
int kill(int tid);

// 查询某个 tid 已被重启了几次（调试用）
int restart_count(int tid);

// 已登记的服务数
int watched_count();

}  // namespace supervisor
