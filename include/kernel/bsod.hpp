// ============================================================================
//  include/kernel/bsod.hpp —— 启动蓝屏（BSoD）
//  ---------------------------------------------------------------------------
//  什么时候用？
//    开机自检 / 初始化阶段检测到**环境问题**时，用蓝屏把错误说清楚。
//    蓝屏发生在启动早期（shell 还没起来），所以必须有**独立的绘制路径**，
//    不能依赖 term（否则会和字符网格、光标状态打架），也不能依赖 IPC。
//
//  致命 vs 非致命（用户 2026-09-19 明确）：
//    致命    → 蓝屏 + 停机，不接受按键
//    非致命  → 蓝屏 + **按 Enter 继续加载**
//
//  继续键为什么是 Enter？
//    "确认并继续"语义最直觉；空格/Y 容易连按误触；任何键盘都有。
//    扫描码 0x1C（松开码 0x9C 忽略，避免连击重复触发）。
//
//  检测项（用户勾选）：
//    1. 内存 / PMM 初始化失败   → 致命
//    2. initrd / 程序加载失败   → 非致命（按 Enter 继续）
//    3. 服务进程创建失败        → 核心服务致命，非核心非致命
//
//  ⚠️ ACPI 不可用**不蓝屏**（用户没勾，且机器上目前确实不可用），
//     维持现状：shell 提示 + shutdown 时上屏诊断。
//  ⚠️ "没有串口" **不蓝屏**，只在 shell 里提示（既有规则）。
// ============================================================================
#pragma once

#include <kernel/types.h>

namespace bsod {

// ---------------------------------------------------------------------------
//  显示蓝屏
// ---------------------------------------------------------------------------
//  subsystem  出错的子系统，如 "initrd / 程序加载"
//  error      错误本身，如 "未找到嵌入的 .xzs 程序（共 0 个）"
//  detail     后果说明，如 "命令程序无法运行，命令将不可用"
//  fatal      true = 停机不接受按键；false = 按 Enter 继续（函数返回）
// ---------------------------------------------------------------------------
void show(const char* subsystem, const char* error, const char* detail, bool fatal);

// 便捷：致命错误（显示后永久停机，不会返回）
void fatal(const char* subsystem, const char* error, const char* detail);

// 便捷：非致命错误（显示后等待 Enter，按下后返回继续加载）
void warn(const char* subsystem, const char* error, const char* detail);

// ---------------------------------------------------------------------------
//  等待 Enter 键
// ---------------------------------------------------------------------------
//  ⚠️ 这是**内核直读 0x60** 的极简路径，与运行时走 IPC 的键盘服务不同。
//     因为蓝屏时用户态键盘服务还没创建，根本拿不到按键。
//
//  读端口时判 bit5(AUXB)：=1 说明是鼠标数据，必须丢弃
//  （这正是之前"动鼠标往命令行灌乱码"那个坑）。
// ---------------------------------------------------------------------------
void wait_enter();

}  // namespace bsod
