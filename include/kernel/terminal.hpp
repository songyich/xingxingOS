// ============================================================================
//  include/kernel/terminal.hpp —— 文本终端
//  ---------------------------------------------------------------------------
//  终端 = 「把字符流画到屏幕上」这层逻辑。它屏蔽掉底层的两种差异：
//
//    后端 A：图形帧缓冲（framebuffer）
//      UEFI 启动、或 BIOS 下 GRUB 切进 VBE 图形模式时用这个。
//      每个字符用 8x16 点阵自己画出来，能显示任意前景/背景色。
//
//    后端 B：VGA 文本模式（0xB8000）
//      老式 BIOS 环境、GRUB 没给帧缓冲时的兜底方案。
//      硬件自己会画字符，我们只管往显存写「ASCII + 属性字节」。
//
//  为什么还要保留 VGA 兜底？
//    有些机器（尤其是老 BIOS）GRUB 切不进图形模式，或者分辨率协商失败。
//    有兜底就不会「黑屏无从下手」——这一点在真机调试时能救命。
// ============================================================================
#pragma once

#include <kernel/types.h>

namespace term {

enum class Backend {
    None,          // 还没初始化
    Framebuffer,   // 图形帧缓冲
    VgaText,       // VGA 文本模式兜底
};

// 初始化：自动挑选后端
// 参数 info_phys = GRUB 递过来的 Multiboot2 信息结构物理地址
void init(u64 info_phys);

// 当前用的是哪个后端
Backend backend();

// 屏幕能显示多少列 / 多少行字符
int columns();
int rows();

// 清屏并把光标移回左上角
void clear();

// 设置前景/背景色（0xRRGGBB）；VGA 后端会就近映射到 16 色
void set_color(u32 fg, u32 bg);

// 输出一个字符（处理 \n \r \t \b 和自动换行、滚屏）
void putc(char c);

// 输出以 '\0' 结尾的字符串
void puts(const char* str);

// 输出指定长度的字符串（遇到 '\0' 提前结束），kprintf 的 %s 会用到
void puts_n(const char* str, int len);

// ---------------------------------------------------------------------------
//  光标闪烁
//  -------------------------------------------------------------------------
//  tick_cursor()  ：由**定时器中断**周期性调用，翻转光标亮/灭
//  cursor_moved() ：光标位置被改动后调用（输入/退格/方向键/清屏等），
//                   让光标立刻重新显示，不等下一个闪烁周期
//
//  两者配合才有好手感：闪烁靠 tick_cursor，跟手靠 cursor_moved。
// ---------------------------------------------------------------------------
void tick_cursor();
void cursor_moved();

}  // namespace term
