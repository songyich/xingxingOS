// ============================================================================
//  include/kernel/gdt.hpp —— 正式 GDT 与 TSS（微内核地基）
//  ---------------------------------------------------------------------------
//  为什么需要一个新的 GDT？
//    boot32.asm 里那个是**临时的**，只有内核代码段和数据段，
//    够用来进入长模式，但要做微内核必须补三样东西：
//
//    1. 用户代码段 / 用户数据段（DPL=3）
//       Ring 3 的段描述符，DPL 必须是 3，否则用户态一执行就 #GP。
//
//    2. TSS
//       当 Ring 3 发生中断时，CPU 需要一个地方找「Ring 0 的栈」。
//       栈切换不能靠软件（CPU 一中断就先切栈），只能靠硬件查 TSS 的 RSP0。
//       没有 TSS，用户态程序收到定时器中断就直接崩。
//
//    3. 段的排列顺序必须满足 sysret 的硬性要求
//       sysret 指令返回用户态时，硬件**固定**这么算：
//           CS = IA32_STAR[63:48] + 16
//           SS = IA32_STAR[63:48] + 8
//       也就是说**用户数据段必须在用户代码段前面，且相隔 8 字节**。
//       这个顺序不能随便排，排错了 sysret 会把段选择子加载错，直接 #GP。
// ============================================================================
#pragma once

#include <kernel/types.h>

namespace gdt {

// ---------------------------------------------------------------------------
//  段选择子
//  -------------------------------------------------------------------------
//  注意 0x28/0x2b、0x30/0x33 这种「同一个段带 RPL」的写法：
//    RPL（请求特权级）占选择子的最低 2 位。
//    0x20 是用户数据段本身，0x23 = 0x20 | 3 表示「以 Ring 3 身份访问」。
// ---------------------------------------------------------------------------
constexpr u16 KERNEL_CODE = 0x08;
constexpr u16 KERNEL_DATA = 0x10;
constexpr u16 USER_DATA32 = 0x18;   // 32 位兼容（暂未用，占位保持对齐）
constexpr u16 USER_DATA   = 0x20;   // 用户数据段
constexpr u16 USER_CODE   = 0x28;   // 用户代码段（64 位）
constexpr u16 TSS         = 0x30;   // TSS，占 16 字节两个条目

// 带 RPL=3 的版本（真正装进段寄存器时用这个）
constexpr u16 USER_CODE_RPL3 = USER_CODE | 3;   // 0x2b
constexpr u16 USER_DATA_RPL3 = USER_DATA | 3;   // 0x23

// ---------------------------------------------------------------------------
//  初始化：建立 GDT、加载 TSS
//  必须在进入用户态之前调用
// ---------------------------------------------------------------------------
void init();

// ---------------------------------------------------------------------------
//  设置当前 CPU 的 RSP0（Ring 0 栈）
//  -------------------------------------------------------------------------
//  每次线程切换都要重新设置：
//    TSS 里的 RSP0 是「下一个线程从 Ring 3 陷入内核时用的栈」。
//    如果切了线程却忘了改 RSP0，新线程的用户态代码一触发中断，
//    CPU 就会把现场压到**上一个线程**的内核栈上——栈被覆盖，必崩。
// ---------------------------------------------------------------------------
void set_kernel_stack(u64 rsp0);

// 给汇编用的 TSS 地址（加载 TR 寄存器需要）
u64 tss_address();

}  // namespace gdt
