#pragma once
#include <kernel/types.h>

// ===========================================================================
//  ACPI —— 高级配置与电源接口
//  ==========================================================================
//  这里只实现**关机**需要的最小子集：
//    找到 RSDP → 找到 FADT → 取 PM1a_CNT 端口 → 从 DSDT 解析 \_S5 → 写端口断电
//
//  为什么要它：
//    以前 `shutdown` 只是打印"可以关闭电源了"然后 hlt，
//    虚拟机/真机都不断电，还得手动关。现在要**真的断电**。
//
//  【微内核分工】
//    机制（写端口断电）在内核，策略（什么时候关机）在用户态电源服务。
// ===========================================================================
namespace acpi {

// 扫描并定位 ACPI 表。成功返回 true。
// 必须在内存管理初始化之后调用（要用恒等映射访问 1MB 以下的区域）。
bool init();

// 是否已经找到可用的关机信息
bool available();
// 把探测过程打到屏幕（用户可见），用于关机失败时的现场诊断
void report_diag();

// 执行 ACPI 关机（断电）。
// 返回 false 表示失败（没找到 ACPI 或写端口无效），调用方应回退到 halt。
bool shutdown();

// 取 PM1a_CNT 端口与 SLP_TYP 值（调试用）
u32 pm1a_cnt_port();
u32 slp_typa();
u32 slp_typb();

}   // namespace acpi
