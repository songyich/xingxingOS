// ============================================================================
//  include/kernel/keyboard.hpp —— PS/2 键盘驱动
//  ---------------------------------------------------------------------------
//  键盘怎么和 CPU 通信？
//    每次按键/松键，键盘控制器都会往数据端口 0x60 放一个字节（叫「扫描码」），
//    然后拉 IRQ1 通知 CPU：「有东西可读了」。
//    CPU 在中断处理里读走这个字节——**读走这个动作本身**就是清中断，
//    不读的话 IRQ1 会一直挂着，再也收不到下一个键。
//
//  扫描码不等于字符：
//    它只表示「第几号键被按下/松开」，跟键帽上印什么无关。
//    从扫描码到字符需要一个映射表，还要处理 Shift、大小写这些修饰键。
//
//  阶段 5 的增强：支持方向键、Home/End 等功能键
//    普通键的扫描码是 1 字节，但方向键这类「扩展键」会先发一个 E0 前缀。
//    比如按上箭头，硬件依次送来 E0、48 两个字节。
//    驱动要记住「刚才收到了 E0」，才能把后面的 48 解释成「上箭头」而不是「小键盘 8」。
//    这些键不对应任何 ASCII 字符，所以用 >= 0x100 的编码单独表示（见 Key 枚举）。
// ============================================================================
#pragma once

#include <kernel/types.h>

namespace keyboard {

// 环形缓冲区大小（能暂存多少个按键）
constexpr int BUFFER_SIZE = 256;

// ---------------------------------------------------------------------------
//  按键编码
//  -------------------------------------------------------------------------
//  0x00~0x7F  普通 ASCII 字符（'a'、'1'、'\n'……）
//  >= 0x100   功能键和方向键，没有对应的 ASCII 字符
// ---------------------------------------------------------------------------
enum Key : u16 {
    // 方向键
    ARROW_UP    = 0x100,
    ARROW_DOWN  = 0x101,
    ARROW_LEFT  = 0x102,
    ARROW_RIGHT = 0x103,

    // 编辑键
    KEY_HOME    = 0x110,
    KEY_END     = 0x111,
    KEY_INSERT  = 0x112,
    KEY_DELETE  = 0x113,
    KEY_PAGEUP  = 0x114,
    KEY_PAGEDN  = 0x115,

    // 功能键
    KEY_F1      = 0x120,   // F2~F12 依次递增
    KEY_F12     = 0x12B,

    KEY_ESC     = 0x130,
    KEY_TAB_LIT = 0x131,   // 字面 Tab（不做补全时直接插入）

    // Ctrl 组合键（沿用 ASCII 控制字符的语义）
    KEY_CTRL_C  = 0x03,    // 中断当前输入
    KEY_CTRL_L  = 0x0C,    // 清屏（换页符）
    KEY_CTRL_U  = 0x15,    // 清空当前行
    KEY_CTRL_D  = 0x04,    // EOF / 退出
};

// 初始化：注册 IRQ1 处理函数并放开中断
void init();

// 缓冲区里是否有待读取的按键
bool has_key();

// 读一个按键；缓冲区为空时返回 0
// 返回值可能是 ASCII 字符，也可能是上面 Key 枚举里的功能键编码
u16 read_key();

// 只看一眼下一个按键，不取走
u16 peek_key();

// 等待并读取一个按键（阻塞，靠 hlt 省电）
u16 wait_key();

// 统计信息
u32 interrupt_count();      // IRQ1 被触发的总次数
u32 key_count();            // 成功转成按键的总数

// 清空缓冲区
void flush();

}  // namespace keyboard
