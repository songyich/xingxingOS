// ============================================================================
//  include/kernel/pmm.hpp —— 物理页帧分配器（Physical Memory Manager）
//  ---------------------------------------------------------------------------
//  为什么需要它？
//    内存管理分两层：物理内存和虚拟内存。
//    虚拟内存负责「让每个程序以为自己独占地址空间」，
//    但最终所有虚拟页都得落到真实的物理页上——
//    「哪些物理页是空闲的、哪些被占用了」这个问题由 PMM 回答。
//
//  为什么用位图？
//    最直观的做法是链表（空闲页串成链），但分配连续多页时很慢。
//    位图把每个物理页的状态压成一个 bit：
//      4GB 内存 / 4KB 页 = 100 万页 = 1M bit = 128KB 位图
//    查找连续空闲页可以一次扫 64 个 bit（一个 u64），速度足够，
//    而且实现简单、行为可预测——教学阶段这两点比极致性能重要。
//
//  分配粒度：4KB（一个页帧）。更大的连续分配由上层（堆）自己切。
// ============================================================================
#pragma once

#include <kernel/types.h>

namespace pmm {

// 页帧大小
constexpr u64 PAGE_SIZE = 4096;

// 位图里每个 u64 管多少个页帧
constexpr u64 BITS_PER_WORD = 64;

// ---------------------------------------------------------------------------
//  初始化：解析 Multiboot2 内存映射，建立位图
//  参数 info_phys = GRUB 递过来的信息结构物理地址
//  必须在 vmm / heap 之前调用
// ---------------------------------------------------------------------------
void init(u64 info_phys);

// ---------------------------------------------------------------------------
//  分配 / 释放
// ---------------------------------------------------------------------------

// 分配一个物理页帧，返回物理地址；内存耗尽返回 0
u64 alloc_frame();

// 分配 count 个**物理上连续**的页帧，返回起始物理地址；失败返回 0
u64 alloc_frames(u64 count);

// 释放一个页帧（addr 必须是 alloc_frame 返回过的、4K 对齐的地址）
void free_frame(u64 addr);

// 释放 count 个连续页帧
void free_frames(u64 addr, u64 count);

// 把某一页标记为「已占用」（用于保护内核、页表、MMIO 等关键区域）
void mark_used(u64 addr);

// ---------------------------------------------------------------------------
//  统计信息（meminfo 命令要用）
// ---------------------------------------------------------------------------
u64 total_memory();      // 探测到的可用物理内存总量（字节）
u64 used_memory();       // 已分配（字节）
u64 free_memory();       // 剩余（字节）
u64 frame_count();       // 管理的页帧总数
u64 used_frames();       // 已占用的页帧数

// ---------------------------------------------------------------------------
//  在指定物理地址以下分配一个页帧
//  -------------------------------------------------------------------------
//  为什么需要这个？
//    页表页本身要被 CPU 读写，而内核目前只能通过
//    「物理地址 + 高半区基址」的方式访问物理内存（低 2GB 才有这层映射）。
//    所以页表所在的物理页必须落在 2GB 以下，否则内核根本改不动它。
//    这是本阶段的简化设计，DEVLOG 里记了完整的替代方案（递归映射）。
// ---------------------------------------------------------------------------
u64 alloc_frame_below(u64 max_addr);

}  // namespace pmm
