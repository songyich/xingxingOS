// ============================================================================
//  include/kernel/isr.hpp —— 中断与异常
//  ---------------------------------------------------------------------------
//  几个名词先对齐：
//
//  IDT（Interrupt Descriptor Table，中断描述符表）
//    一张有 256 项的表，第 n 项登记「第 n 号中断发生时跳到哪里」。
//    CPU 靠 lidt 指令知道这张表在哪。
//
//  中断（Interrupt）vs 异常（Exception）
//    异常 = CPU 自己发现的毛病（除零、访问不存在的页……），编号 0~31
//    中断 = 外部设备喊 CPU（键盘按了、定时器到了），编号 32 起
//    两者共用同一张 IDT，处理流程也一样，所以代码上不必区分。
//
//  中断门（Interrupt Gate）vs 陷阱门（Trap Gate）
//    差别只有一点：进中断门时 CPU 会自动清 IF（关中断），进陷阱门不会。
//    内核一般用中断门，避免嵌套中断把栈搞乱。
//
//  PIC（8259 可编程中断控制器）
//    老机器上的「中断总机」：外部设备先把线接到它，它再转告 CPU。
//    默认 IRQ0~7 对应中断号 0~7，**正好和 CPU 异常撞车**，
//    所以必须重映射——把 IRQ0~15 挪到中断号 32~47。
// ============================================================================
#pragma once

#include <kernel/types.h>

// ---------------------------------------------------------------------------
//  中断栈帧：汇编 stub 压出来的，顺序必须和 isr_stubs.asm 完全对应
//  packed 不能少——否则编译器会在中间插对齐空隙，读到的寄存器全是错的
// ---------------------------------------------------------------------------
struct Registers {
    // push rax..r15 保存下来的通用寄存器
    u64 r15, r14, r13, r12, r11, r10, r9, r8;
    u64 rbp, rdi, rsi, rdx, rcx, rbx, rax;

    // 我们 stub 自己压的
    u64 int_no;        // 中断号
    u64 err_code;      // 错误码（无错误码的异常这里是补的 0）

    // CPU 自动压的
    u64 rip, cs, rflags, rsp, ss;
} __attribute__((packed));

namespace isr {

// 初始化 IDT：登记 256 个入口，然后 lidt 加载
void init();

// 注册一个中断处理函数（一般给 IRQ 用）
// irq 用「中断号」（32 起），不是 IRQ 编号
void register_handler(u8 int_no, void (*handler)(const Registers*));

}  // namespace isr

// 汇编 stub 调用的 C++ 入口（不要手动调用）
// 返回值是「接下来要用的栈指针」——阶段 6 线程切换的挂钩点。
// 没有切换时原样返回传入的 Registers 指针。
extern "C" u64 isr_handler(const Registers* regs);

// 调度器（定义在 kernel/thread.cpp）
namespace sched {
u64 on_interrupt(u64 current_rsp);
}

// ---------------------------------------------------------------------------
//  异常的中文名（诊断信息用）
//  返回 nullptr 表示这个编号没有对应的中文名
// ---------------------------------------------------------------------------
const char* exception_name(u8 int_no);
