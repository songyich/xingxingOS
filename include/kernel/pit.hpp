// ============================================================================
//  include/kernel/pit.hpp —— 8253/8254 可编程间隔定时器
//  ---------------------------------------------------------------------------
//  PIT 是 PC 上最老的时间源：给它一个分频值，它就按固定频率敲 IRQ0。
//  内核靠数这些「滴答」来知道时间流逝， preemptive 调度也依赖它。
//
//  基准频率是 1193182 Hz（约 1.19 MHz，来自老式彩色显示器的晶振，历史遗留）。
//  想要 N Hz 的中断，就写分频值 1193182 / N。
// ============================================================================
#pragma once

#include <kernel/types.h>

namespace pit {

// 内核默认的心跳频率（Hz）。
// 100 Hz 意味着每秒 100 次中断、每 10 毫秒一次——
// 对人眼够用（键盘响应即时），对内核开销也小。
constexpr u32 DEFAULT_FREQUENCY = 100;

// 初始化并按给定频率开始打拍
void init(u32 frequency = DEFAULT_FREQUENCY);

// 当前配置的实际频率
u32 frequency();

// 自开机以来累计的 tick 数
u64 ticks();

// 运行时间：毫秒 / 秒
u64 uptime_ms();
u64 uptime_seconds();

// 忙等指定的毫秒数（没有调度器之前只能空转）
void busy_wait_ms(u32 ms);

}  // namespace pit
