// ============================================================================
//  include/kernel/usermode.hpp —— 用户态进程创建（微内核改造的核心）
//  ============================================================================
#pragma once

#include <kernel/types.h>

namespace usermode {

// ---------------------------------------------------------------------------
//  用户空间布局
//  -------------------------------------------------------------------------
//  用户进程不能和内核抢地址，必须有自己独立的一块低地址空间。
//  典型的 Unix 布局：代码从 0x400000 开始（4MB 处），栈在最高处往下长。
// ---------------------------------------------------------------------------
constexpr u64 USER_CODE_BASE = 0x0000000000400000ull;   // 代码段起点
// 用户态服务的**可写数据段**（services.o 的 .data/.bss）。
// 必须和代码段一样落在用户空间，否则 PC32 相对寻址会溢出（见 linker.ld）。
constexpr u64 USER_DATA_BASE = 0x0000000000500000ull;
constexpr u64 USER_STACK_TOP = 0x0000000080000000ull;   // 栈顶（2GB 处）
constexpr u64 USER_STACK_SIZE = 64 * 1024;              // 64KB 用户栈
constexpr u64 KERNEL_STACK_SIZE = 32 * 1024;            // 32KB 内核栈

// ---------------------------------------------------------------------------
//  初始化：准备内核栈等基础设施
// ---------------------------------------------------------------------------
void init();

// ---------------------------------------------------------------------------
//  创建一个用户态进程
//  -------------------------------------------------------------------------
//  entry_virt：内核里入口函数的虚拟地址（代码编译进内核镜像，
//              运行时映射到用户空间并在 Ring 3 执行）
//  返回 tid，失败返回 -1
// ---------------------------------------------------------------------------
int create_user_process(const char* name, u64 entry_virt, int priority);

// ---------------------------------------------------------------------------
//  创建用户页表（独立地址空间）
//  -------------------------------------------------------------------------
//  新页表只保留内核映射，用户空间从零开始。
//  这样每个用户进程**看不到**别的进程的内存，也看不到低地址物理内存。
// ---------------------------------------------------------------------------
u64 create_user_pml4();

// ---------------------------------------------------------------------------
//  在当前进程地址空间映射一段用户可访问的页
// ---------------------------------------------------------------------------
bool map_user_pages(u64 virt, u64 phys, u64 count, bool executable);

// ---------------------------------------------------------------------------
//  重启一个已死亡的用户态服务（复用 tid 槽位，P2 崩溃自愈）
//  -------------------------------------------------------------------------
//  成功返回 0，失败返回 -1。
//  复用 tid 是关键：服务目录和其他服务持有的 tid 引用全部继续有效。
// ---------------------------------------------------------------------------
int respawn_user_process(int tid, u64 entry_virt);

// IPC 共享页的内核虚拟地址（清残留状态时用）。未分配返回 0。
u64 ipc_page_virt();

// ---------------------------------------------------------------------------
//  从 initrd 里的 ELF 映像创建用户进程（「万物皆可程序」的核心）
//  -------------------------------------------------------------------------
//  prog_name：程序名（如 "help"），在 initrd 里查找
//  argc/argv：传给程序的命令行参数（argv 是**用户空间**指针数组）
//  返回 tid，失败返回 -1
// ---------------------------------------------------------------------------
int create_elf_process(const char* prog_name, int argc, char** argv_user);

// 系统调用入口：a1=名字指针 a2=名字长度 a3=argv a4=argc
int spawn_program(u64 name_ptr, u64 name_len, u64 argv_ptr, u64 argc);

// ---------------------------------------------------------------------------
//  用户态服务进程用的简易输出（走 syscall 调试通道）
// ---------------------------------------------------------------------------
void init_services();

}  // namespace usermode
