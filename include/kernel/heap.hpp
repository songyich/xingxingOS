// ============================================================================
//  include/kernel/heap.hpp —— 内核堆（kmalloc / kfree）
//  ---------------------------------------------------------------------------
//  PMM 和 VMM 解决的是「以页为单位」的内存管理，但内核经常只需要几十、
//  几百字节（一个结构体、一段字符串）。每次都给一整页 4KB 太浪费了。
//  堆就是在页分配器之上再做一层「切碎 + 回收」的工作。
//
//  本阶段的实现：显式双向链表 + 首次适配（first-fit）
//    - 每个内存块前面带一个头部，记录大小和是否空闲
//    - 分配时从头扫，找到第一个够大的空闲块
//    - 块太大就切成两块，剩下的还回空闲链表
//    - 释放时标记空闲，并和前后相邻的空闲块合并（防碎片化）
//
//  为什么不一开始就用 slab / 伙伴系统？
//    那些是为性能和抗碎片设计的，代码量大得多。
//    链表版只有一百多行，行为直观、好调试，适合作为第一个堆。
//    等阶段 6 有多线程、阶段 7 有用户程序后，再换更好的实现也来得及。
// ============================================================================
#pragma once

#include <kernel/types.h>

namespace heap {

// ---------------------------------------------------------------------------
//  堆的起始虚拟地址
//  -------------------------------------------------------------------------
//  选这个地址的考量（这里踩过坑，值得细看）：
//
//    一开始选了 0xffffffffc0000000，结果 vmm::map_page 直接拒绝，
//    报「当前是 2MB 大页映射」。为什么？
//    因为 0xffffffff8xxxxxxx 这一整段（PML4[511]）已经被 boot32.asm
//    用 **2MB 大页** 整块映射过了——它把物理 0~2GB 恒等地映射到高半区。
//    在一个已经是大页的区域里再插入 4KB 页，必须先把大页拆成 512 个小页，
//    否则 PD 项里存的「大页物理基址」会被当成下一级页表地址去解引用。
//
//    更省事也更安全的办法：干脆挑一个**完全没被用过**的 PML4 槽位。
//    PML4 槽位划分：
//      [511] 0xffffff8000000000  内核高半区（boot 用 2MB 大页填满）
//      [510] 0xffffff0000000000  帧缓冲等 MMIO
//      [509] 0xfffffe8000000000  ← 空闲，堆就用这里
//
//    这样堆的地址空间是全新的，页表可以从零一层层建起来，
//    既不用拆大页，也彻底避开了和内核/MMIO 冲突的可能。
// ---------------------------------------------------------------------------
constexpr u64 HEAP_START = 0xfffffe8000000000ull;

// 单次向页分配器申请的增长量（16 页 = 64KB）
constexpr u64 HEAP_EXPAND_PAGES = 16;

// 堆的上限（防止无限制扩张把地址空间吃光）
constexpr u64 HEAP_MAX_SIZE = 64 * 1024 * 1024;   // 64MB

// 初始化堆
void init();

// 堆是否已初始化
bool ready();

// ---------------------------------------------------------------------------
//  分配 / 释放
// ---------------------------------------------------------------------------
void* kmalloc(usize size);
void  kfree(void* ptr);

// 分配并把内存清零（calloc 的单元素版）
void* kzalloc(usize size);

// 重新调整已分配块的大小；尽量原地扩张，否则搬家
void* krealloc(void* ptr, usize new_size);

// ---------------------------------------------------------------------------
//  统计与自检
// ---------------------------------------------------------------------------
u64 used_bytes();       // 已分配出去的字节数
u64 total_bytes();      // 堆当前总大小（已向页分配器申请的部分）
u64 free_bytes();       // 空闲字节数
u32 block_count();      // 当前块数量（碎片化程度的粗略指标）

// 打印堆布局（调试用）
void dump();

}  // namespace heap
