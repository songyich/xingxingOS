// ============================================================================
//  include/kernel/vmm.hpp —— 虚拟内存管理（Virtual Memory Manager）
//  ---------------------------------------------------------------------------
//  虚拟内存解决什么问题？
//    让每个程序都「以为」自己独占了整个地址空间。
//    CPU 发出的地址是虚拟地址，硬件（MMU）查页表翻译成物理地址。
//    于是两个程序可以都用 0x400000 而不冲突——它们背后是两块不同的物理内存。
//
//  x86_64 的 4 级页表：
//    虚拟地址 48 位被切成 5 段：
//      47..39  PML4 下标
//      38..30  PDPT 下标
//      29..21  PD   下标
//      20..12  PT   下标
//      11..0   页内偏移
//    每一级都是 512 项、每项 8 字节，正好一页 4KB。
//
//  「按需建立」的关键：
//    4 级全建满是 512 GB 的页表，没人这么干。
//    实际做法是：用到哪一段才建哪一层的表项，
//    这靠页表项的 P（Present）位实现——P=0 时 CPU 会触发页错误，
//    我们（在阶段 4 的简化版里是调用者）负责把缺的那层补上。
//
//  本阶段提供的是「显式映射」接口（map_page 手动调用），
//  真正的「缺页异常时自动补全」属于更进阶的设计，暂不做。
// ============================================================================
#pragma once

#include <kernel/types.h>

namespace vmm {

// ---------------------------------------------------------------------------
//  页表项标志位
// ---------------------------------------------------------------------------
constexpr u64 PAGE_PRESENT  = (1ull << 0);   // 这一项有效
constexpr u64 PAGE_WRITABLE = (1ull << 1);   // 可写
constexpr u64 PAGE_USER     = (1ull << 2);   // 用户态可访问（阶段 7 用）
constexpr u64 PAGE_PWT      = (1ull << 3);   // 写穿透缓存
constexpr u64 PAGE_PCD      = (1ull << 4);   // 禁用缓存（MMIO 要设）
constexpr u64 PAGE_ACCESSED = (1ull << 5);   // CPU 访问过会自动置位
constexpr u64 PAGE_DIRTY    = (1ull << 6);   // CPU 写过会自动置位
constexpr u64 PAGE_PS       = (1ull << 7);   // PD 项：PS=1 表示 2MB 大页
constexpr u64 PAGE_NX       = (1ull << 63);  // 禁止执行（防代码注入）

constexpr u64 PAGE_SIZE     = 4096;
constexpr u64 PAGE_MASK     = ~(PAGE_SIZE - 1);

// 常用的组合
constexpr u64 FLAGS_KERNEL  = PAGE_PRESENT | PAGE_WRITABLE;
constexpr u64 FLAGS_MMIO    = PAGE_PRESENT | PAGE_WRITABLE | PAGE_PCD | PAGE_NX;

// ---------------------------------------------------------------------------
//  初始化：接管 boot32.asm 建的页表
//  必须在 pmm 之后调用（建新页表需要申请物理页）
// ---------------------------------------------------------------------------
void init();

// 返回当前 PML4 的物理地址（就是 CR3 里的值）
u64 pml4_phys();

// ---------------------------------------------------------------------------
//  映射 / 解除映射
// ---------------------------------------------------------------------------

// 把虚拟地址 virt 映射到物理地址 phys。
// 中间的页表层如果不存在会自动创建（从 PMM 申请物理页）。
// 返回是否成功。
bool map_page(u64 virt, u64 phys, u64 flags = FLAGS_KERNEL);

// 可指定页表的版本（创建用户进程时用）
//
// 为什么需要它？
//   普通 map_page 固定操作**内核页表**。但给新建的用户进程
//   映射内存时，要写的是**新进程的页表**，不是内核的。
//
//   注意：调用它时**不要**先切 CR3 到新页表。
//   页表层是用物理地址经内核窗口访问的，切了 CR3 之后
//   那个窗口可能就不在新页表里，访问会直接 #PF。
//   正确做法：待在内核页表下，用这个函数直接改新页表。
bool map_page_in(u64 pml4_phys, u64 virt, u64 phys, u64 flags);
bool map_pages_in(u64 pml4_phys, u64 virt, u64 phys, u64 count, u64 flags);

// 连续映射 count 个页（virt 与 phys 各自连续递增）
bool map_pages(u64 virt, u64 phys, u64 count, u64 flags = FLAGS_KERNEL);

// 解除映射（只清页表项，不释放物理页——释放与否由调用者决定）
void unmap_page(u64 virt);

// 查询虚拟地址对应的物理地址；未映射返回 0
u64 get_phys(u64 virt);

// 按指定页表翻译虚拟地址
u64 get_phys_in(u64 pml4_phys, u64 virt);

// 按当前 CR3（即当前进程的页表）翻译 —— 翻译用户指针必须用这个
u64 get_phys_current(u64 virt);

// 虚拟地址是否已映射
bool is_mapped(u64 virt);

// 修改已存在映射的权限（不改变物理地址）
bool set_flags(u64 virt, u64 flags);

// ---------------------------------------------------------------------------
//  刷新 TLB
//  -------------------------------------------------------------------------
//  为什么必须刷新？
//    CPU 会把「虚拟地址 -> 物理地址」的翻译结果缓存进 TLB。
//    改了页表不去通知它，它会继续用旧的翻译——
//    典型症状是：改完页表访问那个地址，行为完全不符合预期。
// ---------------------------------------------------------------------------
void flush_tlb(u64 virt);       // 只刷一个地址（invlpg）
void flush_tlb_all();           // 全刷（重新加载 CR3）

}  // namespace vmm
