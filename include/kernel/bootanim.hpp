// ============================================================================
//  include/kernel/bootanim.hpp —— 开机动画（五角星螺旋 + 背景上移）
//  ---------------------------------------------------------------------------
//  分镜（用户逐帧描述，2026-09-19）：
//    ① 螺旋入场   星星从左上角螺旋旋转飞向屏幕中心
//    ② 收缩消失   到位后突然收缩成一个点消失
//    ③ 加载       屏幕保持黑，界面画到离屏缓冲
//    ④ 突然放出   加载完成的那一刻，星星从中间由小变大猛地放出
//    ⑤ 背景上移   已加载好的界面整体向上移入屏幕
//
//  ⭐ 重要：这个「五角星 + 光晕」造型是 **xingxingOS 的官方图标**。
//    以后 UI / 窗口 / 关于页 / 文件管理器都复用 draw_star()。
//
//  为什么动画要分"屏上"和"离屏"两个阶段？
//    ① ② 发生在 pmm::init 之前，还没有内存管理器，只能在真帧缓冲上画；
//    ③ 需要一块和屏幕一样大的离屏缓冲，必须等 pmm + vmm 就绪。
// ============================================================================
#pragma once

#include <kernel/types.h>

namespace bootanim {

// ---------------------------------------------------------------------------
//  系统官方图标：五角星 + 光晕
// ---------------------------------------------------------------------------
//  参数：
//    cx, cy      中心坐标
//    radius      外接圆半径（像素）
//    rot_deg     旋转角度（度，可负可大于 360）
//    color       基色，光晕由它按亮度梯度派生
//
//  光晕做法：三层同心星形，外大内小、外暗内亮，
//            亮度梯度 18% / 45% / 100%（在 .cpp 里可调）
// ---------------------------------------------------------------------------
void draw_star(int cx, int cy, int radius, int rot_deg, u32 color);

// ---------------------------------------------------------------------------
//  阶段 ①②：螺旋入场 + 收缩消失
// ---------------------------------------------------------------------------
//  调用时机：term::init() 之后、pmm::init() 之前
//  返回 false 表示没有可用帧缓冲（动画整体跳过）
// ---------------------------------------------------------------------------
bool play_intro();

// ---------------------------------------------------------------------------
//  阶段 ③：切换到离屏缓冲
// ---------------------------------------------------------------------------
//  调用时机：pmm::init() + vmm::init() 之后
//  之后所有绘制（终端、汉字、鼠标）都进离屏，屏幕保持全黑
//
//  返回 false 表示离屏分配失败 ——
//  此时降级：界面直接画到屏幕，跳过 ⑤ 的上移动画（其余动画照常）
// ---------------------------------------------------------------------------
bool begin_offscreen();

// ---------------------------------------------------------------------------
//  阶段 ④⑤：星星放出 + 背景上移揭示界面
// ---------------------------------------------------------------------------
//  调用时机：全部加载完成、切换到用户态之前
// ---------------------------------------------------------------------------
void play_outro();

// ---------------------------------------------------------------------------
//  收尾：切回真帧缓冲并释放离屏缓冲
// ---------------------------------------------------------------------------
void finish();

// 当前是否在离屏模式（供调试/降级判断）
bool offscreen_active();

}  // namespace bootanim
